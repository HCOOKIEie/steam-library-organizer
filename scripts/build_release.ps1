[CmdletBinding()]
param(
    [ValidatePattern('^\d+\.\d+\.\d+$')]
    [string] $Version = '1.0.1',

    [ValidateSet('OneFile', 'OneDir', 'Both')]
    [string] $Layout = 'Both',

    [switch] $SkipTests,

    [switch] $KeepEnvironment
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$scriptRoot = Split-Path -Parent $MyInvocation.MyCommand.Path
$projectRoot = [IO.Path]::GetFullPath((Join-Path $scriptRoot '..'))
$buildRoot = [IO.Path]::GetFullPath((Join-Path $projectRoot '.build'))
$venvRoot = [IO.Path]::GetFullPath((Join-Path $projectRoot '.venv-release'))
$tempRoot = [IO.Path]::GetFullPath((Join-Path $buildRoot 'temp-release'))
$workRoot = [IO.Path]::GetFullPath((Join-Path $buildRoot 'pyinstaller-release'))
$distRoot = [IO.Path]::GetFullPath((Join-Path $projectRoot 'dist'))
$releaseRoot = [IO.Path]::GetFullPath((Join-Path $distRoot 'release'))
$specPath = Join-Path $buildRoot 'SteamLibraryOrganizer.spec'
$requirementsPath = Join-Path $projectRoot 'requirements-lock.txt'
$generatedRoot = Join-Path $buildRoot 'generated'
$generatedVersionPath = Join-Path $generatedRoot 'SteamLibraryOrganizer.version.txt'
$managedEnvironmentNames = @(
    'TEMP',
    'TMP',
    'PYTHONNOUSERSITE',
    'PIP_DISABLE_PIP_VERSION_CHECK',
    'PIP_CACHE_DIR',
    'PYINSTALLER_CONFIG_DIR',
    'PATH',
    'PYTHONPATH',
    'PYTHONHOME',
    'CONDA_PREFIX',
    'VIRTUAL_ENV',
    'SLO_BUILD_MODE',
    'SLO_VERSION_FILE'
)
$originalEnvironment = @{}
foreach ($name in $managedEnvironmentNames) {
    $originalEnvironment[$name] = [Environment]::GetEnvironmentVariable($name, 'Process')
}

function Assert-ChildPath {
    param(
        [Parameter(Mandatory)] [string] $Candidate,
        [Parameter(Mandatory)] [string] $Parent
    )

    $fullCandidate = [IO.Path]::GetFullPath($Candidate).TrimEnd('\')
    $fullParent = [IO.Path]::GetFullPath($Parent).TrimEnd('\')
    $prefix = $fullParent + [IO.Path]::DirectorySeparatorChar
    if (-not $fullCandidate.StartsWith($prefix, [StringComparison]::OrdinalIgnoreCase)) {
        throw "Refusing to modify a path outside $fullParent`: $fullCandidate"
    }
    return $fullCandidate
}

function Remove-SafeDirectory {
    param(
        [Parameter(Mandatory)] [string] $Path,
        [Parameter(Mandatory)] [string] $AllowedParent
    )

    $safePath = Assert-ChildPath -Candidate $Path -Parent $AllowedParent
    if (Test-Path -LiteralPath $safePath) {
        Remove-Item -LiteralPath $safePath -Recurse -Force
    }
}

function Invoke-Checked {
    param(
        [Parameter(Mandatory)] [string] $Description,
        [Parameter(Mandatory)] [scriptblock] $Command
    )

    Write-Host "`n==> $Description" -ForegroundColor Cyan
    # Cmdlets do not update LASTEXITCODE. Reset it so a successful cmdlet-only
    # block cannot inherit a stale failure from an earlier native command.
    $LASTEXITCODE = 0
    & $Command
    $commandSucceeded = $?
    $exitCode = $LASTEXITCODE
    if (-not $commandSucceeded -or $exitCode -ne 0) {
        throw "$Description failed with exit code $exitCode"
    }
}

function Write-Utf8NoBom {
    param(
        [Parameter(Mandatory)] [string] $Path,
        [Parameter(Mandatory)] [string] $Content
    )

    $encoding = New-Object Text.UTF8Encoding($false)
    [IO.File]::WriteAllText($Path, $Content, $encoding)
}

function Get-PeMachine {
    param([Parameter(Mandatory)] [string] $Path)

    $stream = [IO.File]::OpenRead([IO.Path]::GetFullPath($Path))
    $reader = New-Object IO.BinaryReader($stream)
    try {
        if ($reader.ReadUInt16() -ne 0x5A4D) {
            throw "Not a PE file: $Path"
        }
        $stream.Position = 0x3C
        $peOffset = $reader.ReadUInt32()
        $stream.Position = $peOffset
        if ($reader.ReadUInt32() -ne 0x00004550) {
            throw "Invalid PE signature: $Path"
        }
        return $reader.ReadUInt16()
    }
    finally {
        $reader.Dispose()
        $stream.Dispose()
    }
}

function Assert-X64Pe {
    param([Parameter(Mandatory)] [string] $Path)

    $machine = Get-PeMachine -Path $Path
    if ($machine -ne 0x8664) {
        throw ('Expected AMD64 PE machine 0x8664, found 0x{0:X4}: {1}' -f $machine, $Path)
    }
    Write-Host "Validated AMD64 PE: $Path" -ForegroundColor DarkGreen
}

function New-VersionResource {
    param(
        [Parameter(Mandatory)] [string] $Path,
        [Parameter(Mandatory)] [string] $SemanticVersion
    )

    $parts = $SemanticVersion.Split('.')
    $numericVersion = '{0}, {1}, {2}, 0' -f $parts[0], $parts[1], $parts[2]
    $displayVersion = "$SemanticVersion.0"
    $content = @"
# Generated by scripts/build_release.ps1. Do not edit this generated copy.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers=($numericVersion),
    prodvers=($numericVersion),
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0),
  ),
  kids=[
    StringFileInfo([
      StringTable(
        '040904B0',
        [
          StringStruct('CompanyName', 'HCOOKIEie'),
          StringStruct('FileDescription', 'Steam Library Organizer'),
          StringStruct('FileVersion', '$displayVersion'),
          StringStruct('InternalName', 'SteamLibraryOrganizer'),
          StringStruct('LegalCopyright', 'Copyright (C) 2026 HCOOKIEie'),
          StringStruct('OriginalFilename', 'SteamLibraryOrganizer.exe'),
          StringStruct('ProductName', 'Steam Library Organizer'),
          StringStruct('ProductVersion', '$displayVersion'),
        ],
      )
    ]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])]),
  ],
)
"@
    Write-Utf8NoBom -Path $Path -Content $content
}

function Invoke-PyInstallerBuild {
    param(
        [Parameter(Mandatory)] [ValidateSet('onefile', 'onedir')] [string] $Mode,
        [Parameter(Mandatory)] [string] $PythonPath
    )

    $modeWorkRoot = Join-Path $workRoot $Mode
    $modeDistRoot = Join-Path $distRoot $Mode
    Remove-SafeDirectory -Path $modeWorkRoot -AllowedParent $workRoot
    Remove-SafeDirectory -Path $modeDistRoot -AllowedParent $distRoot
    New-Item -ItemType Directory -Path $modeWorkRoot, $modeDistRoot -Force | Out-Null

    $env:SLO_BUILD_MODE = $Mode
    $env:SLO_VERSION_FILE = $generatedVersionPath
    Invoke-Checked "Build $Mode package with PyInstaller" {
        & $PythonPath -I -m PyInstaller `
            --noconfirm `
            --clean `
            --distpath $modeDistRoot `
            --workpath $modeWorkRoot `
            $specPath
    }

    $analysisFiles = Get-ChildItem -LiteralPath $modeWorkRoot -Recurse -File |
        Where-Object { $_.Extension -in '.toc', '.txt' }
    $environmentLeaks = $analysisFiles | Select-String `
        -Pattern 'anaconda|miniconda|AppData[\\/]+Roaming[\\/]+Python|[\\/]\.codex[\\/]|codex-runtimes' `
        -CaseSensitive:$false
    if ($environmentLeaks) {
        $locations = ($environmentLeaks | Select-Object -First 10 | ForEach-Object Path) -join ', '
        throw "The $Mode analysis contains a known contaminated environment path: $locations"
    }

    $sitePackageLines = $analysisFiles | Select-String -Pattern 'site-packages' -CaseSensitive:$false
    $foreignSitePackages = $sitePackageLines | Where-Object {
        $normalized = $_.Line.Replace('\\', '\').Replace('/', '\')
        $normalized.IndexOf($venvRoot, [StringComparison]::OrdinalIgnoreCase) -lt 0
    }
    if ($foreignSitePackages) {
        $locations = ($foreignSitePackages | Select-Object -First 10 | ForEach-Object Path) -join ', '
        throw "The $Mode analysis contains site-packages outside $venvRoot`: $locations"
    }

    $virtualEnvironmentLines = $analysisFiles | Select-String `
        -Pattern '[\\/](\.venv|venv|env)[^\\/]*[\\/]' `
        -CaseSensitive:$false
    $foreignVirtualEnvironments = $virtualEnvironmentLines | Where-Object {
        $normalized = $_.Line.Replace('\\', '\').Replace('/', '\')
        $normalized.IndexOf($venvRoot, [StringComparison]::OrdinalIgnoreCase) -lt 0
    }
    if ($foreignVirtualEnvironments) {
        $locations = ($foreignVirtualEnvironments | Select-Object -First 10 | ForEach-Object Path) -join ', '
        throw "The $Mode analysis contains another virtual environment: $locations"
    }

    # Analysis-00.toc is PyInstaller's pre-filter input record. Inspect the
    # final package manifests to confirm excluded assets did not ship.
    $packageManifests = $analysisFiles | Where-Object { $_.Name -ne 'Analysis-00.toc' }
    $foreignAssets = $packageManifests | Select-String `
        -Pattern 'pywebview-android\.jar|WebBrowserInterop\.x86\.dll'
    if ($foreignAssets) {
        $locations = ($foreignAssets | Select-Object -First 10 | ForEach-Object Path) -join ', '
        throw "The $Mode package contains foreign pywebview assets: $locations"
    }

    if ($Mode -eq 'onefile') {
        Assert-X64Pe -Path (Join-Path $modeDistRoot 'SteamLibraryOrganizer.exe')
    }
    else {
        Assert-X64Pe -Path (Join-Path $modeDistRoot 'SteamLibraryOrganizer\SteamLibraryOrganizer.exe')
    }
}

Push-Location $projectRoot
try {
    Write-Host "Building Steam Library Organizer $Version from an isolated CPython 3.13.2 environment." -ForegroundColor Green

    New-Item -ItemType Directory -Path $buildRoot -Force | Out-Null
    Remove-SafeDirectory -Path $tempRoot -AllowedParent $buildRoot
    New-Item -ItemType Directory -Path $tempRoot -Force | Out-Null
    $env:TEMP = $tempRoot
    $env:TMP = $tempRoot
    $env:PYTHONNOUSERSITE = '1'
    $env:PIP_DISABLE_PIP_VERSION_CHECK = '1'
    $env:PIP_CACHE_DIR = Join-Path $buildRoot 'pip-cache'
    $env:PYINSTALLER_CONFIG_DIR = Join-Path $buildRoot 'pyinstaller-config'
    $env:PYTHONPATH = $null
    $env:PYTHONHOME = $null
    $env:CONDA_PREFIX = $null
    $env:VIRTUAL_ENV = $null

    $baseInfoJson = & py -3.13 -c "import json, platform, sys; print(json.dumps({'executable': sys.executable, 'base_prefix': sys.base_prefix, 'implementation': platform.python_implementation(), 'machine': platform.machine(), 'version': list(sys.version_info[:3])}))"
    if ($LASTEXITCODE -ne 0) {
        throw 'CPython 3.13.2 x64 was not found. Install the 64-bit python.org build and ensure the py launcher is available.'
    }
    $baseInfo = $baseInfoJson | ConvertFrom-Json
    if ($baseInfo.implementation -ne 'CPython' -or ($baseInfo.version -join '.') -ne '3.13.2') {
        throw "Expected CPython 3.13.2, found $($baseInfo.implementation) $($baseInfo.version -join '.')"
    }
    if ($baseInfo.machine -notmatch 'AMD64|x86_64') {
        throw "Expected 64-bit Python, found machine '$($baseInfo.machine)'"
    }
    if (([string] $baseInfo.base_prefix) -match 'anaconda|miniconda|conda') {
        throw "The py -3.13 interpreter is Conda-based: $($baseInfo.base_prefix)"
    }

    $basePython = [string] $baseInfo.executable

    # PyInstaller searches PATH for dependent DLLs. A strict allowlist prevents
    # unrelated applications from supplying a same-named runtime DLL.
    $basePythonRoot = Split-Path -Parent $basePython
    $cleanPathEntries = @(
        (Join-Path $venvRoot 'Scripts'),
        $basePythonRoot,
        (Join-Path $env:SystemRoot 'System32'),
        $env:SystemRoot,
        (Join-Path $env:SystemRoot 'System32\Wbem'),
        (Join-Path $env:SystemRoot 'System32\WindowsPowerShell\v1.0')
    ) | Where-Object { $_ } | Select-Object -Unique
    $env:PATH = $cleanPathEntries -join [IO.Path]::PathSeparator

    if (-not $KeepEnvironment) {
        Remove-SafeDirectory -Path $venvRoot -AllowedParent $projectRoot
    }
    $venvPython = Join-Path $venvRoot 'Scripts\python.exe'
    if (-not (Test-Path -LiteralPath $venvPython)) {
        Invoke-Checked 'Create isolated CPython 3.13.2 virtual environment' {
            & $basePython -m venv $venvRoot
        }
    }

    $venvInfoJson = & $venvPython -I -c "import json, platform, sys; print(json.dumps({'base_prefix': sys.base_prefix, 'implementation': platform.python_implementation(), 'machine': platform.machine(), 'version': list(sys.version_info[:3])}))"
    if ($LASTEXITCODE -ne 0) {
        throw "Unable to inspect release environment: $venvRoot"
    }
    $venvInfo = $venvInfoJson | ConvertFrom-Json
    if ($venvInfo.implementation -ne 'CPython' -or ($venvInfo.version -join '.') -ne '3.13.2') {
        throw "Release environment must use CPython 3.13.2; found $($venvInfo.implementation) $($venvInfo.version -join '.')"
    }
    if ($venvInfo.machine -notmatch 'AMD64|x86_64' -or ([string] $venvInfo.base_prefix) -match 'anaconda|miniconda|conda') {
        throw "Release environment is not a clean CPython x64 environment: $($venvInfo.base_prefix)"
    }

    Invoke-Checked 'Install release-only dependencies' {
        & $venvPython -m pip install `
            --require-virtualenv `
            --only-binary=:all: `
            --no-binary=proxy_tools `
            --no-input `
            -r $requirementsPath
    }
    Invoke-Checked 'Validate dependency graph' {
        & $venvPython -m pip check
    }
    Invoke-Checked 'Verify WebView2/.NET, tkinter and embedded UI imports' {
        & $venvPython -c "import clr, tkinter, webview; from steam_modern import load_ui_html; import steam_desktop; html=load_ui_html(); assert '<style' in html and 'steamOrganizerBridgeReady' in html; import System; print('CLR:', System.Environment.Version); print('Tk:', tkinter.TkVersion); print('UI bytes:', len(html.encode('utf-8')))"
    }
    Invoke-Checked 'Verify application and release versions match' {
        & $venvPython -I -c "import sys; sys.path.insert(0, sys.argv[1]); import steam_modern; assert steam_modern.APP_VERSION == sys.argv[2], f'APP_VERSION={steam_modern.APP_VERSION}, release={sys.argv[2]}'" $projectRoot $Version
    }

    if (-not $SkipTests) {
        Invoke-Checked 'Run unit tests in the clean release environment' {
            & $venvPython -m unittest discover -s tests -v
        }
    }

    New-Item -ItemType Directory -Path $generatedRoot -Force | Out-Null
    New-VersionResource -Path $generatedVersionPath -SemanticVersion $Version
    Remove-SafeDirectory -Path $workRoot -AllowedParent $buildRoot
    New-Item -ItemType Directory -Path $workRoot -Force | Out-Null
    Remove-SafeDirectory -Path $releaseRoot -AllowedParent $distRoot
    New-Item -ItemType Directory -Path $releaseRoot -Force | Out-Null

    if ($Layout -in 'OneFile', 'Both') {
        Invoke-PyInstallerBuild -Mode onefile -PythonPath $venvPython
        $oneFileSource = Join-Path $distRoot 'onefile\SteamLibraryOrganizer.exe'
        $oneFileTarget = Join-Path $releaseRoot "SteamLibraryOrganizer-$Version-win-x64.exe"
        Copy-Item -LiteralPath $oneFileSource -Destination $oneFileTarget

        # Keep the repository-root convenience binary in sync, but only after
        # PyInstaller has completed successfully.
        $rootExe = Join-Path $projectRoot 'SteamLibraryOrganizer.exe'
        Copy-Item -LiteralPath $oneFileSource -Destination $rootExe -Force
        $rootHash = (Get-FileHash -LiteralPath $rootExe -Algorithm SHA256).Hash
        Write-Utf8NoBom `
            -Path (Join-Path $projectRoot 'SteamLibraryOrganizer.exe.sha256') `
            -Content "$rootHash  SteamLibraryOrganizer.exe`n"
    }

    if ($Layout -in 'OneDir', 'Both') {
        Invoke-PyInstallerBuild -Mode onedir -PythonPath $venvPython
        $oneDirSource = Join-Path $distRoot 'onedir\SteamLibraryOrganizer'
        $portableName = "SteamLibraryOrganizer-$Version-win-x64-portable"
        $portableStage = Join-Path $releaseRoot $portableName
        Copy-Item -LiteralPath $oneDirSource -Destination $portableStage -Recurse
        foreach ($document in 'README.md', 'THIRD_PARTY_NOTICES.md') {
            $documentPath = Join-Path $projectRoot $document
            if (Test-Path -LiteralPath $documentPath) {
                Copy-Item -LiteralPath $documentPath -Destination $portableStage
            }
        }
        $thirdPartyLicenses = Join-Path $projectRoot 'THIRD_PARTY_LICENSES'
        if (Test-Path -LiteralPath $thirdPartyLicenses -PathType Container) {
            Copy-Item `
                -LiteralPath $thirdPartyLicenses `
                -Destination (Join-Path $portableStage 'THIRD_PARTY_LICENSES') `
                -Recurse
        }
        $portableZip = Join-Path $releaseRoot "$portableName.zip"
        Compress-Archive -Path (Join-Path $portableStage '*') -DestinationPath $portableZip -CompressionLevel Optimal
        Remove-SafeDirectory -Path $portableStage -AllowedParent $releaseRoot
    }

    # The direct one-file EXE is accompanied by a compact license archive.
    # The recommended onedir ZIP already contains the same files internally.
    $licenseStage = Join-Path $buildRoot 'license-release-stage'
    Remove-SafeDirectory -Path $licenseStage -AllowedParent $buildRoot
    New-Item -ItemType Directory -Path $licenseStage -Force | Out-Null
    $noticesPath = Join-Path $projectRoot 'THIRD_PARTY_NOTICES.md'
    if (Test-Path -LiteralPath $noticesPath) {
        Copy-Item -LiteralPath $noticesPath -Destination $licenseStage
    }
    $licensesPath = Join-Path $projectRoot 'THIRD_PARTY_LICENSES'
    if (Test-Path -LiteralPath $licensesPath -PathType Container) {
        Copy-Item `
            -LiteralPath $licensesPath `
            -Destination (Join-Path $licenseStage 'THIRD_PARTY_LICENSES') `
            -Recurse
    }
    $licenseArchive = Join-Path $releaseRoot "SteamLibraryOrganizer-$Version-third-party-licenses.zip"
    Compress-Archive `
        -Path (Join-Path $licenseStage '*') `
        -DestinationPath $licenseArchive `
        -CompressionLevel Optimal
    Remove-SafeDirectory -Path $licenseStage -AllowedParent $buildRoot

    $freezePath = Join-Path $releaseRoot 'BUILD-DEPENDENCIES.txt'
    $freeze = (& $venvPython -m pip freeze --all) -join "`n"
    Write-Utf8NoBom -Path $freezePath -Content ($freeze + "`n")

    $hashTargets = Get-ChildItem -LiteralPath $releaseRoot -File |
        Where-Object { $_.Name -ne 'SHA256SUMS.txt' } |
        Sort-Object Name
    $hashLines = foreach ($file in $hashTargets) {
        $hash = (Get-FileHash -LiteralPath $file.FullName -Algorithm SHA256).Hash.ToLowerInvariant()
        "$hash  $($file.Name)"
    }
    Write-Utf8NoBom -Path (Join-Path $releaseRoot 'SHA256SUMS.txt') -Content (($hashLines -join "`n") + "`n")

    Write-Host "`nRelease artifacts:" -ForegroundColor Green
    Get-ChildItem -LiteralPath $releaseRoot -File | Select-Object Name, Length, LastWriteTime
}
finally {
    Pop-Location
    foreach ($name in $managedEnvironmentNames) {
        [Environment]::SetEnvironmentVariable(
            $name,
            $originalEnvironment[$name],
            'Process'
        )
    }
}
